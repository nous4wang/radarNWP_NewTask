    pat = re.compile(r"(?m)^#{2,3} 4\.(\d+)\s")
    marks = list(pat.finditer(sec4))
    nums = [int(m.group(1)) for m in marks]
    expected = list(range(0, 23)) + [24]
    if nums != expected:
        raise SystemExit(f"unexpected section split: {nums}\nexpected {expected}")

