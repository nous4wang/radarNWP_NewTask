    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(sec4)
        by_sec["4." + m.group(1)] = sec4[m.start():end].rstrip() + "\n"

    spec_by_sec = {row[0]: row for row in SPEC}
    missing = set(by_sec) - {"4.0"} - set(spec_by_sec)
    if missing:
        raise SystemExit(f"missing card spec for sections: {sorted(missing)}")

    # 1. one detail file per attempt, verbatim body
