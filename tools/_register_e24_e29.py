def build(spec: dict) -> str:
    head = f"""# {spec['num']} · {spec['title']}

> 按 `docs/experiments/README.md` 的范式建立；判据写入时间 **{STAMP}**，
> 早于本轮任何算力投入（MASTER §11.7 R4）。MASTER 里只有大白话卡片，
> 完整结果放本文件。

| 字段 | 内容 |
|---|---|
| **编号** | `{spec['num']}` |
| **对应 MASTER 小节** | `{spec['sec']}` |
| **这次想干什么（大白话）** | {spec['goal']} |
| **具体怎么改 / 怎么试** | {spec['how']} |
| **判据（先写后跑，{STAMP}）** | 见下面第 2 节逐条核对表；参照锚点均引自 MASTER 既有承重结论，不用结果反推门槛。 |
| **简要结果** | {spec['result']} |
| **裁决** | {spec['verdict']} |
| **证据层级** | {spec['evidence']} |
| **数值采信（§11.6）** | {spec['device']} |
| **主要产物与复现路径** | {spec['artifacts']} |
| **不可再写的说法** | {spec['nowrite']} |
"""
    rows = "\n".join(
        f"| {name} | {cond} | 待填 | 待判 |"
        for name, cond in spec["criteria"]
    )
    tail = COMMON_TAIL.format(stamp=STAMP, criteria_rows=rows, limits=spec["limits"])
    return head + tail


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for spec in SPECS:
        p = OUT / spec["file"]
        if p.exists():
            raise SystemExit(f"refuse to overwrite existing experiment file: {p}")
        p.write_text(build(spec), encoding="utf-8")
        print(f"created {p.relative_to(ROOT)}  ({spec['num']} -> {spec['sec']})")
    print(f"total {len(SPECS)} files; criteria timestamp {STAMP}")


if __name__ == "__main__":
    main()
